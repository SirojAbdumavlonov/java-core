package lessons.lesson02;

import java.util.Scanner;

public class SceneQuest {

    public void callSceneGame(){

        Scanner scanner = new Scanner(System.in);

        int choice = scanner.nextInt();

        System.out.println("""
                Сцена 1: Пробуждение
                
                Ты приходишь в себя на холодном песке у берега озера. Вокруг — туман, ночь, ни души.
                Телефон в кармане почти разряжен (1%). В другом кармане — спичка и клочок бумаги с надписью:
                "Не доверяй голосам. Иди к северу"
                
                Выбор:
                1) Пойти на восток, туда, где в тумане мерцает свет.  (→ Сцена 2A)
                2) Пойти на север, как советует записка.              (→ Сцена 2B)
                3) Остаться у озера, может, кто-то придёт.            (→ Сцена 2C)
                """);
        System.out.print("Введи 1, 2 или 3: ");

        if (choice == 1) {
            System.out.println("""
                    --- Сцена 2A: Восточный свет ---

                    Ты идёшь на свет и находишь старую электростанцию. Внезапно загорается прожектор.
                    Голос в громкоговорителе: «Стоять. Идентификация...»
                    Ты ничего не понимаешь.

                    Выбор:
                    1) Ответить: «Я человек, я потерялся!»  (→ Сцена 3A)
                    2) Убежать назад в лес.                 (→ Сцена 3B)
                    """);
            System.out.print("Введи 1 или 2: ");
            choice = scanner.nextInt();
            if (choice == 1) {
                System.out.println("""
                        --- Сцена 3A: Попытка общения ---

                        Ты кричишь, но свет слепит тебя. Из темноты появляется фигура в противогазе.
                        Вас усыпляют. Очнулся ты уже в лаборатории. Ты стал частью эксперимента.

                        === Концовка: Неудача ===
                        Описание: Неудача — исчезновение, смерть, или ты стал частью эксперимента.
                        """);
            } else {
                System.out.println("""
                        --- Сцена 3B: Побег ---

                        Ты бежишь, но спотыкаешься. Прожектор гаснет. Что-то двигается в кустах.
                        Ты исчез без следа.

                        === Концовка: Неудача ===
                        Описание: Неудача — исчезновение, смерть.
                        """);
            }
        } else if (choice == 2) {
            System.out.println("""
                    --- Сцена 2B: Северный путь ---

                    Ты следуешь на север и находишь заброшенную деревню. Дома пусты, но в одном — следы костра и дневник.
                    "Озеро просыпается в полнолуние. Не верь голосам. Прячься до рассвета."

                    Выбор:
                    1) Остаться в доме до рассвета. (→ Сцена 3C)
                    2) Выйти и идти дальше в туман. (→ Сцена 3D)
                    """);
            System.out.print("Введи 1 или 2: ");
            choice = scanner.nextInt();
            if (choice == 1) {
                System.out.println("""
                        --- Сцена 3C: Ожидание ---

                        Ты сидишь у костра. Проходят часы. На рассвете из тумана выходит группа людей — выжившие.
                        Они помогают тебе выбраться.

                        === Концовка: Победа ===
                        Описание: Спасение, эвакуация.
                        """);
            } else {
                System.out.println("""
                        --- Сцена 3D: Поиски ---

                        Ты блуждаешь в тумане и выходишь к маяку. Там — старая рация. Связь удаётся установить.
                        На следующий день — эвакуация.

                        === Концовка: Победа ===
                        Описание: Спасение, эвакуация.
                        """);
            }
        } else {
            System.out.println("""
                    --- Сцена 2C: Ожидание у озера ---

                    Ты остаёшься на месте. Из тумана слышишь детский голос:
                    «Помоги мне… пожалуйста…» Тебя охватывает страх.

                    Выбор:
                    1) Пойти на голос.       (→ Сцена 3E)
                    2) Убежать прочь в лес. (→ Сцена 3F)
                    """);
            System.out.print("Введи 1 или 2: ");
            choice = scanner.nextInt();
            if (choice == 1) {
                System.out.println("""
                        --- Сцена 3E: Девочка ---

                        Ты идёшь на голос и видишь девочку в белом. Она улыбается и исчезает в воде.
                        Вокруг тебя — тени. Ты не можешь двигаться.

                        === Концовка: Проклятие озера ===
                        Описание: Попал под влияние озера.
                        """);
            } else {
                System.out.println("""
                        --- Сцена 3F: Побег в лес ---

                        Ты бежишь прочь. Натыкаешься на подземный люк. Внутри — бункер. Там — доказательства эксперимента:
                        мониторы, карты, журналы.

                        Выбор:
                        1) Разрушить центр управления. (→ Сцена 4A)
                        2) Присоединиться к проекту.   (→ Сцена 4B)
                        """);
                System.out.print("Введи 1 или 2: ");
                choice = scanner.nextInt();
                if (choice == 1) {
                    System.out.println("""
                            --- Сцена 4A: Разрушение ---

                            Ты активируешь самоуничтожение. Озеро начинает светиться. Тьма уходит.
                            Ты спас мир… но погиб.

                            === Концовка: Герой ===
                            Описание: Спас мир, но погиб.
                            """);
                } else {
                    System.out.println("""
                            --- Сцена 4B: Присоединение ---

                            Ты входишь в проект. Тебе дают новое имя. Ты становишься частью того, что раньше преследовало тебя.

                            === Концовка: Тайный участник ===
                            Описание: Стал частью эксперимента.
                            """);
                }
            }
        }

        System.out.println("""
                --- Справка по концовкам ---
                Победа           — Спасение, эвакуация
                Неудача          — Исчезновение, смерть
                Проклятие озера  — Попал под влияние озера
                Герой            — Спас мир, но погиб
                Тайный участник  — Стал частью эксперимента
                """);

        scanner.close();
    }
}
